-- family_members
--   select: same-family active viewer; Hidden Admin rows invisible to everyone
--   except Hidden Admin viewers (§43.18). No insert through the API — members
--   are created by the server only. Chief may update roles/status within family.
drop policy if exists "family_members_select_masked" on public.family_members;
create policy "family_members_select_masked" on public.family_members
  for select using (
    public.famora_is_active_member(public.family_members."familyId")
    and (
      public.family_members."internalRole" <> 'HIDDEN_ADMIN'::internal_role
      or public.famora_may_view_hidden_admin(public.family_members."familyId")
    )
  );

drop policy if exists "family_members_update_manage" on public.family_members;
create policy "family_members_update_manage" on public.family_members
  for update using (
    public.famora_has_internal_role(public.family_members."familyId", array['FAMILY_CHIEF','HIDDEN_ADMIN']::internal_role[])
    and public.family_members."internalRole" <> 'HIDDEN_ADMIN'::internal_role
  )
  with check (
    public.famora_has_internal_role(public.family_members."familyId", array['FAMILY_CHIEF','HIDDEN_ADMIN']::internal_role[])
    and public.family_members."internalRole" <> 'HIDDEN_ADMIN'::internal_role
  );

drop policy if exists "family_member_settings_own" on public.family_member_settings;
create policy "family_member_settings_own" on public.family_member_settings
  using (
    exists (
      select 1 from public.family_members fm
      where fm.id = public.family_member_settings."memberId"
        and fm."userId" = public.famora_auth_uid()
        and fm.status = 'ACTIVE'
    )
  );

