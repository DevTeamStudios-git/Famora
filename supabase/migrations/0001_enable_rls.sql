-- Famora — RLS bootstrap (migration 0001)
-- ============================================
-- Applies AFTER Prisma generated the schema (tables, enums, columns). Run with:
--   supabase db push  |  psql "…" -f supabase/migrations/0001_enable_rls.sql
--
-- Security model
-- --------------
--  • RLS is the database floor (least privilege). The authoritative layer is
--    the application server (src/lib/authorization: hasPermission +
--    FamilyGrant merges). Policies here are deliberately conservative and may
--    NOT re-implement every FamilyGrant rule — they only guarantee a safe
--    minimum: nobody outside the family, no inactive member, no raw exposure
--    of Hidden Admin (§43.16–§43.24).
--  • Column names are camelCase exactly as generated by Prisma
--    (e.g. "familyId", "userId", "internalRole") — they MUST be double-quoted
--    in SQL. Table & enum names are snake_case (`@@map`).
--  • Hidden Admin rows (family_members / family_whitelist) are only readable
--    by a Hidden Admin viewer. No other role can observe them — even raw SQL
--    is blocked by policy (§43.18 no detectability).

-- ---------------------------------------------------------------------------
-- 1. Helper functions (security definer, no RLS recursion)
-- ---------------------------------------------------------------------------

create or replace function public.famora_auth_uid() returns uuid
language sql stable security definer set search_path = public, pg_temp
as $$
  select auth.uid();
$$;

create or replace function public.famora_is_active_member("pFamilyId" uuid) returns boolean
language sql stable security definer set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.family_members fm
    where fm."userId" = public.famora_auth_uid()
      and fm."familyId" = "pFamilyId"
      and fm.status = 'ACTIVE'
  );
$$;

create or replace function public.famora_has_internal_role("pFamilyId" uuid, "pRoles" internal_role[]) returns boolean
language sql stable security definer set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.family_members fm
    where fm."userId" = public.famora_auth_uid()
      and fm."familyId" = "pFamilyId"
      and fm.status = 'ACTIVE'
      and fm."internalRole" = any("pRoles")
  );
$$;

-- Viewer is an active member of at least one family that the target member belongs to.
create or replace function public.famora_can_see_member("pUserId" uuid) returns boolean
language sql stable security definer set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.family_members viewer
    where viewer."userId" = public.famora_auth_uid()
      and viewer.status = 'ACTIVE'
      and exists (
        select 1
        from public.family_members target
        where target."userId" = "pUserId"
          and target."familyId" = viewer."familyId"
          and target.status = 'ACTIVE'
      )
  );
$$;

-- Viewer sees Hidden Admin rows only when the viewer is a Hidden Admin (§43.18).
create or replace function public.famora_may_view_hidden_admin("pFamilyId" uuid) returns boolean
language sql stable security definer set search_path = public, pg_temp
as $$
  select public.famora_has_internal_role("pFamilyId", array['HIDDEN_ADMIN']::internal_role[]);
$$;

