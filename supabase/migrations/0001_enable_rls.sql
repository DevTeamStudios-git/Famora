-- conversation access is derived from conversation_members (private per family).
drop policy if exists "conversations_select_members" on public.conversations;
create policy "conversations_select_members" on public.conversations
  for select using (
    exists (
      select 1
      from public.conversation_members cm
      join public.family_members fm on fm.id = cm."memberId"
      where cm."conversationId" = public.conversations.id
        and fm."userId" = public.famora_auth_uid()
        and fm.status = 'ACTIVE'
    )
  );

drop policy if exists "conversation_members_select_self" on public.conversation_members;
create policy "conversation_members_select_self" on public.conversation_members
  for select using (
    exists (
      select 1
      from public.family_members fm
      where fm.id = public.conversation_members."memberId"
        and fm."userId" = public.famora_auth_uid()
        and fm.status = 'ACTIVE'
    )
  );

drop policy if exists "messages_select_participant" on public.messages;
create policy "messages_select_participant" on public.messages
  for select using (
    public.messages."deletedAt" is null
    and exists (
      select 1
      from public.conversation_members cm
      join public.family_members fm on fm.id = cm."memberId"
      where cm."conversationId" = public.messages."conversationId"
        and fm."userId" = public.famora_auth_uid()
        and fm.status = 'ACTIVE'
    )
  );

drop policy if exists "messages_insert_send" on public.messages;
create policy "messages_insert_send" on public.messages
  for insert with check (
    exists (
      select 1
      from public.conversation_members cm
      join public.family_members fm on fm.id = cm."memberId"
      where cm."conversationId" = public.messages."conversationId"
        and fm."userId" = public.famora_auth_uid()
        and fm.status = 'ACTIVE'
    )
    and public.messages."senderMemberId" in (
      select id from public.family_members fm2
      where fm2."userId" = public.famora_auth_uid() and fm2.status = 'ACTIVE'
    )
  );

-- edit own message; moderators may delete any (soft).
drop policy if exists "messages_update_author" on public.messages;
create policy "messages_update_author" on public.messages
  for update using (
    exists (
      select 1
      from public.family_members fm
      where fm.id = public.messages."senderMemberId"
        and fm."userId" = public.famora_auth_uid()
        and fm.status = 'ACTIVE'
    )
  )
  with check (
    exists (
      select 1
      from public.family_members fm
      where fm.id = public.messages."senderMemberId"
        and fm."userId" = public.famora_auth_uid()
        and fm.status = 'ACTIVE'
    )
  );

