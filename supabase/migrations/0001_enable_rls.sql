-- users: readable by any member of a shared family; a user may update self.
drop policy if exists "users_select_members" on public.users;
create policy "users_select_members" on public.users
  for select using (public.famora_can_see_member(public.users.id));

drop policy if exists "users_update_self" on public.users;
create policy "users_update_self" on public.users
  for update using (public.users.id = public.famora_auth_uid())
  with check (public.users.id = public.famora_auth_uid());

-- user_settings / user_devices: owner only.
drop policy if exists "user_settings_owner" on public.user_settings;
create policy "user_settings_owner" on public.user_settings
  using (public.user_settings."userId" = public.famora_auth_uid());

drop policy if exists "user_devices_owner" on public.user_devices;
create policy "user_devices_owner" on public.user_devices
  using (public.user_devices."userId" = public.famora_auth_uid());

