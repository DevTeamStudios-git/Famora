-- 2. Enable RLS on every table (Prisma-created). Idempotent.
-- ---------------------------------------------------------------------------

do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'users','user_settings','user_devices',
    'families','family_settings','family_features',
    'family_members','family_member_settings','family_grants','family_whitelist',
    'permissions','role_permissions',
    'conversations','conversation_members','messages','message_edits',
    'message_attachments','message_reactions','message_read_states',
    'saved_messages','pinned_messages',
    'polls','poll_options','poll_votes',
    'event_categories','calendar_events','event_attendees','event_reminders',
    'tasks','task_assignments','task_comments','task_history',
    'notebooks','notebook_pages','notebook_page_versions','shared_page_grants','page_tags',
    'file_blobs','folders','files',
    'announcements','announcement_reads',
    'family_contacts','recipes','recipe_comments',
    'albums','memories','memory_assets','memory_comments','memory_reactions',
    'notifications','user_notification_preferences',
    'audit_logs','activity_events'
  ] loop
    execute format('alter table public.%I enable row level security;', tbl);
  end loop;
end
$$;

