import {existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mobile = path.join(root, 'mobile');
const windows = process.platform === 'win32';
const args = process.argv.slice(2);
const debug = args.includes('--debug');
const variant = debug ? 'debug' : 'release';
const sdkCandidates = [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT,
  process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, 'Android', 'Sdk'),
  process.env.HOME && path.join(process.env.HOME, 'Library', 'Android', 'sdk'),
  process.env.HOME && path.join(process.env.HOME, 'Android', 'Sdk')].filter(Boolean);
const sdk = sdkCandidates.find(candidate => existsSync(path.join(candidate, 'platform-tools')));
if (!sdk) throw new Error('Android SDK not found. Install Android Studio and set ANDROID_HOME to its SDK folder.');
const javaCandidates = [process.env.JAVA_HOME,
  windows && 'C:/Program Files/Android/Android Studio/jbr',
  !windows && '/Applications/Android Studio.app/Contents/jbr/Contents/Home'].filter(Boolean);
const java = javaCandidates.find(candidate => existsSync(path.join(candidate, 'bin', windows ? 'java.exe' : 'java')));
if (!java) throw new Error('Java 17 or newer is required. Set JAVA_HOME or install Android Studio with its bundled JBR.');
const apiBase = (process.env.FAMORA_API_URL || 'https://famora-app-five.vercel.app').replace(/\/$/, '');
const parsed = new URL(apiBase);
if (parsed.protocol !== 'https:' && !['localhost', '127.0.0.1', '10.0.2.2'].includes(parsed.hostname))
  throw new Error('FAMORA_API_URL must use HTTPS, except for the local Android emulator.');
if (parsed.username || parsed.password || parsed.search || parsed.hash || parsed.pathname !== '/')
  throw new Error('FAMORA_API_URL must be a server origin without credentials, path, query or fragment.');

const environment = {...process.env, JAVA_HOME: java, ANDROID_HOME: sdk, ANDROID_SDK_ROOT: sdk,
  PATH: path.join(java, 'bin') + path.delimiter + process.env.PATH};
function run(command, commandArgs, cwd) {
  const result = spawnSync(command, commandArgs, {cwd, env: environment, stdio: 'inherit'});
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status || 1);
}
if (!existsSync(path.join(mobile, 'node_modules', 'react-native', 'package.json'))) {
  const npmCli = [process.env.npm_execpath, path.join(path.dirname(process.execPath), 'node_modules', 'npm', 'bin', 'npm-cli.js')]
    .find(candidate => candidate && candidate.endsWith('npm-cli.js') && existsSync(candidate));
  if (npmCli) run(process.execPath, [npmCli, 'ci'], mobile);
  else if (!windows) run('npm', ['ci'], mobile);
  else throw new Error('npm CLI not found. Install Node.js with npm or run npm ci inside the mobile folder first.');
}
mkdirSync(path.join(mobile, 'src', 'generated'), {recursive: true});
function writeIfChanged(file, content) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content) writeFileSync(file, content);
}
writeIfChanged(path.join(mobile, 'src', 'generated', 'config.ts'),
  `// Generated by npm run android:apk. Public server origin only; no credentials.\nexport const API_BASE_URL = ${JSON.stringify(apiBase)};\nexport default {apiBase: API_BASE_URL};\n`);
writeIfChanged(path.join(mobile, 'android', 'local.properties'), `sdk.dir=${sdk.replaceAll('\\', '/').replace(':', '\\:')}\n`);
console.log(`Building Famora ${variant} APK for ${apiBase}`);
console.log('This development APK uses the bundled development signing key. Use a private release key for store distribution.');
const architectures = process.env.FAMORA_ANDROID_ARCHS || 'arm64-v8a,x86_64';
if (!/^(arm64-v8a|x86_64|armeabi-v7a|x86)(,(arm64-v8a|x86_64|armeabi-v7a|x86))*$/.test(architectures)) throw new Error('Invalid FAMORA_ANDROID_ARCHS.');
const gradleArgs = [`assemble${debug ? 'Debug' : 'Release'}`, `-PreactNativeArchitectures=${architectures}`, '--console=plain', '--max-workers=2'];
if (args.includes('--instrumentation')) gradleArgs.unshift('assembleDebugAndroidTest');
// Invoke the same wrapper JAR directly, avoiding Windows shell argument interpolation.
run(path.join(java, 'bin', windows ? 'java.exe' : 'java'), ['-Dorg.gradle.appname=gradlew', '-classpath', 'gradle/wrapper/gradle-wrapper.jar', 'org.gradle.wrapper.GradleWrapperMain', ...gradleArgs], path.join(mobile, 'android'));
const apk = path.join(mobile, 'android', 'app', 'build', 'outputs', 'apk', variant, `app-${variant}.apk`);
if (!existsSync(apk)) throw new Error('Gradle completed without producing the expected APK.');
mkdirSync(path.join(root, 'artifacts'), {recursive: true});
const destination = path.join(root, 'artifacts', debug ? 'Famora-debug.apk' : 'Famora.apk');
copyFileSync(apk, destination);
console.log(`APK ready: ${destination}`);
